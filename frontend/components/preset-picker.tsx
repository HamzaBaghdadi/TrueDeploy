"use client";

import { ChevronDown, FileCode2, Info, Loader2, Settings2 } from "lucide-react";
import { useState } from "react";
import { api, type Preset } from "@/lib/api";
import { CopyButton } from "@/components/copy-button";
import { Notice } from "@/components/notice";
import { Button } from "@/components/ui/button";
import { Dialog, DialogContent, DialogDescription, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Select, SelectContent, SelectGroup, SelectItem, SelectLabel, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Switch } from "@/components/ui/switch";
import { cn } from "@/lib/utils";

export const OWN_DOCKERFILE = "own";
const KINDS = ["Static site", "Server-rendered", "Backend"];

/** Chooses between the repo's Dockerfile and a framework preset, with its options. */
export function PresetPicker({
  presets,
  value,
  options,
  port,
  onChange,
}: {
  presets: Preset[];
  value: string; // preset id, or OWN_DOCKERFILE
  options: Record<string, string>;
  port: number;
  onChange: (id: string, options: Record<string, string>) => void;
}) {
  const preset = presets.find((p) => p.id === value);
  const [advanced, setAdvanced] = useState(false);
  const [preview, setPreview] = useState<{ busy: boolean; files?: Record<string, string>; error?: string } | null>(null);

  // Show the default until the user changes a value; only changed values are stored.
  const val = (key: string) => options[key] ?? preset?.options?.find((o) => o.key === key)?.default ?? "";
  const set = (key: string, v: string) => onChange(value, { ...options, [key]: v });

  async function showFiles() {
    if (!preset) return;
    setPreview({ busy: true });
    try {
      setPreview({ busy: false, files: await api.previewPreset(preset.id, options, port) });
    } catch (e) {
      setPreview({ busy: false, error: (e as Error).message });
    }
  }

  const visible = (preset?.options ?? []).filter((o) => advanced || !o.advanced);
  const hasAdvanced = (preset?.options ?? []).some((o) => o.advanced);

  return (
    <div className="space-y-3">
      <div className="space-y-1.5">
        <Label>Dockerfile</Label>
        <Select value={value} onValueChange={(id) => onChange(id, {})}>
          <SelectTrigger className="w-full sm:w-96">
            <SelectValue />
          </SelectTrigger>
          <SelectContent className="max-h-96">
            <SelectItem value={OWN_DOCKERFILE}>The repository&apos;s own Dockerfile</SelectItem>
            {KINDS.map((kind) => (
              <SelectGroup key={kind}>
                <SelectLabel>{kind}: generated by TrueDeploy</SelectLabel>
                {presets
                  .filter((p) => p.kind === kind)
                  .map((p) => (
                    <SelectItem key={p.id} value={p.id}>
                      {p.name}
                    </SelectItem>
                  ))}
              </SelectGroup>
            ))}
          </SelectContent>
        </Select>
        <p className="text-[12px] text-muted-foreground">
          {preset
            ? `${preset.description} The Dockerfile is written at deploy time; your repository isn't changed.`
            : "Uses the Dockerfile in the app folder. No Dockerfile? Pick your framework and TrueDeploy writes one."}
        </p>
      </div>

      {preset && (
        <div className="space-y-3 rounded-lg border border-border bg-background/40 p-3">
          <div className="grid gap-3 sm:grid-cols-2">
            {visible.map((o) =>
              o.type === "bool" ? (
                <div key={o.key} className="flex items-start justify-between gap-3 sm:col-span-2">
                  <Label htmlFor={`po-${o.key}`} className="flex-col items-start gap-0.5 font-normal">
                    <span className="text-sm">{o.label}</span>
                    {o.hint && <span className="text-[12px] text-muted-foreground">{o.hint}</span>}
                  </Label>
                  <Switch id={`po-${o.key}`} checked={val(o.key) === "true"} onCheckedChange={(v) => set(o.key, String(v))} />
                </div>
              ) : (
                <div key={o.key} className={cn("space-y-1", (o.key === "start" || o.key === "build" || o.key === "before" || o.key === "api_upstream") && "sm:col-span-2")}>
                  <Label htmlFor={`po-${o.key}`} className="text-xs text-muted-foreground">
                    {o.label}
                  </Label>
                  <Input
                    id={`po-${o.key}`}
                    className="font-mono text-xs"
                    value={val(o.key)}
                    placeholder={o.default || (o.key === "before" ? "optional" : "")}
                    onChange={(e) => set(o.key, e.target.value)}
                    spellCheck={false}
                  />
                  {o.hint && <p className="text-[11px] text-muted-foreground">{o.hint}</p>}
                </div>
              ),
            )}
          </div>

          {preset.notes && preset.notes.length > 0 && (
            <ul className="space-y-1 border-t border-border pt-2 text-[12px] text-muted-foreground">
              {preset.notes.map((n) => (
                <li key={n} className="flex gap-2">
                  <Info className="mt-0.5 size-3.5 shrink-0" />
                  {n}
                </li>
              ))}
            </ul>
          )}

          <div className="flex flex-wrap gap-2">
            {hasAdvanced && (
              <Button type="button" variant="ghost" size="sm" onClick={() => setAdvanced(!advanced)}>
                <Settings2 /> {advanced ? "Fewer options" : "More options"}
                <ChevronDown className={cn("transition-transform", advanced && "rotate-180")} />
              </Button>
            )}
            <Button type="button" variant="outline" size="sm" onClick={() => void showFiles()}>
              {preview?.busy ? <Loader2 className="animate-spin" /> : <FileCode2 />}
              View generated files
            </Button>
          </div>
        </div>
      )}

      <Dialog open={!!preview && !preview.busy} onOpenChange={(o) => !o && setPreview(null)}>
        <DialogContent className="sm:max-w-3xl">
          <DialogHeader>
            <DialogTitle>{preset?.name}: generated files</DialogTitle>
            <DialogDescription>
              Written to <span className="font-mono">.truedeploy/</span> in the app folder on every deploy. To customize them, copy them into
              your repository and choose &quot;The repository&apos;s own Dockerfile&quot; (adjust the nginx.conf path in it).
            </DialogDescription>
          </DialogHeader>
          {preview?.error && <Notice tone="error">{preview.error}</Notice>}
          <div className="max-h-[60vh] space-y-3 overflow-auto">
            {Object.entries(preview?.files ?? {})
              .sort(([a], [b]) => a.localeCompare(b))
              .map(([name, body]) => (
                <div key={name} className="overflow-hidden rounded-lg border border-border">
                  <div className="flex items-center justify-between border-b border-border bg-muted px-3 py-1.5">
                    <span className="font-mono text-xs">{name}</span>
                    <CopyButton text={body} label={`Copy ${name}`} />
                  </div>
                  <pre className="selectable overflow-auto bg-background/60 p-3 font-mono text-[11px] leading-relaxed">{body}</pre>
                </div>
              ))}
          </div>
        </DialogContent>
      </Dialog>
    </div>
  );
}
